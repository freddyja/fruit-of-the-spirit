export const messages = { en, es, pt }

const greetingKeys = [
  'greetingMorning',
  'greetingAfternoon',
  'greetingEvening',
  'greetingMorningNamed',
  'greetingAfternoonNamed',
  'greetingEveningNamed',
] as const satisfies readonly MessageKey[]

export function translate(
  language: Language,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = messages[language][key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

/** The blessing is a second line. If it repeats the greeting, it is omitted. */
export function blessingBeside(greeting: string, blessing: string): string | null {
  if (greeting.trim().toLocaleLowerCase() === blessing.trim().toLocaleLowerCase()) return null
  return blessing
}

export function greetingDiffersFromBlessing(language: Language): boolean {
  const blessing = messages[language].greetingBlessing
  return greetingKeys.every((key) => {
    const sample = messages[language][key].replaceAll('{name}', 'Name')
    return blessingBeside(sample, blessing) !== null
  })
}
